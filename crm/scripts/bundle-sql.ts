/**
 * Joins every migration (in order) into supabase/setup.sql, so setting up Supabase is ONE paste into the SQL Editor.
 * Every migration is safe to run again, so pasting setup.sql on a database that already has some of them is fine.
 *   npm run bundle-sql
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = [
  "-- Triangle Resells CRM: the whole database setup in one file (generated by `npm run bundle-sql`; don't edit by hand).",
  `-- ${files.length} migrations: ${files.join(", ")}. Safe to run again.`,
  ...files.map((f) => `\n-- ===================== ${f} =====================\n${readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()}\n`),
].join("\n");
writeFileSync(path.join(dir, "..", "setup.sql"), out);
console.log(`Wrote supabase/setup.sql (${files.length} migrations, ${Math.round(out.length / 1024)} KB)`);
